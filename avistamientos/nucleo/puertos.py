"""Contratos del núcleo, sin dependencias de Flask o SQLite."""
from datetime import date
from typing import Protocol


class Reloj(Protocol):
    def hoy(self) -> date:
        """Fecha de referencia de la aplicación."""


class RepositorioAvistamientos(Protocol):
    """Puerto secundario: la aplicación lo dirige. Devuelve datos simples, nunca filas de una base."""

    def listar(self) -> list[dict]: ...
    def obtener(self, identificador: int) -> dict | None: ...
    def crear(self, datos: dict) -> dict: ...
    def actualizar(self, identificador: int, datos: dict) -> dict | None: ...
    def eliminar(self, identificador: int) -> bool: ...
    def resumen(self) -> list[dict]: ...


class GestionAvistamientos(Protocol):
    """Puerto primario: dirige la aplicación. Lo pueden usar HTTP, una consola o las pruebas."""

    def listar(self) -> list[dict]: ...
    def obtener(self, identificador: int) -> dict: ...
    def crear(self, datos: object) -> dict: ...
    def actualizar(self, identificador: int, datos: object) -> dict: ...
    def eliminar(self, identificador: int) -> None: ...
    def resumen(self) -> list[dict]: ...
